export function voiceInstruction(replyLength: "short" | "normal") {
  const length = replyLength === "normal"
    ? "مختصر ولی کامل؛ حداکثر چهار جمله."
    : "خیلی کوتاه؛ یک یا دو جمله.";
  return VOICE_SYSTEM_INSTRUCTION.replace("{{REPLY_LENGTH}}", length);
}

